// 支持的语言
enum class AppLanguage(val tag: String) {
    ZH("zh"),
    EN("en");

    companion object {
        fun fromTag(tag: String?): AppLanguage =
            entries.firstOrNull { it.tag == tag } ?: ZH
    }
}

// 语言状态
object I18n {
    var language by mutableStateOf(AppLanguage.ZH)
        private set

    fun set(value: AppLanguage) {
        language = value
    }

    val strings: Strings
        get() = if (language == AppLanguage.EN) StringsEn else StringsZh

    fun isEnglish(): Boolean = language == AppLanguage.EN
}

